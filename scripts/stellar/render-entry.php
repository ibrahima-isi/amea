<?php

declare(strict_types=1);

/**
 * Generates a thin, secret-free document root index.php pinned to one fixed
 * application identity (public or staff) and external private paths.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$options = [];
foreach (array_slice($argv, 1) as $argument) {
    if (!preg_match('/^--(role|release-root|config|state-dir|output)=(.+)$/s', $argument, $match) || isset($options[$match[1]])) {
        fwrite(STDERR, "Usage: php scripts/stellar/render-entry.php --role=public|staff --release-root=DIR --config=FILE --state-dir=DIR [--output=FILE]\n");
        exit(2);
    }
    $options[$match[1]] = $match[2];
}

foreach (['role', 'release-root', 'config', 'state-dir'] as $required) {
    if (empty($options[$required])) {
        fwrite(STDERR, "Missing required option --{$required}.\n");
        exit(2);
    }
}

$role = $options['role'];
if (!in_array($role, ['public', 'staff'], true)) {
    fwrite(STDERR, "Role must be public or staff.\n");
    exit(2);
}

foreach (['release-root', 'config', 'state-dir'] as $pathOption) {
    $value = $options[$pathOption];
    if (!str_starts_with($value, '/') || str_contains($value, "\0") || str_contains($value, '..')) {
        fwrite(STDERR, "Option --{$pathOption} must be a clean absolute path.\n");
        exit(2);
    }
}

$releaseRoot = rtrim($options['release-root'], '/');
$configFile = $options['config'];
$stateDir = rtrim($options['state-dir'], '/');

$exportSingle = static function (string $value): string {
    return "'" . str_replace(["\\", "'"], ["\\\\", "\\'"], $value) . "'";
};

$autoloadPath = $releaseRoot . '/vendor/autoload.php';
$php = "<?php\n"
    . "declare(strict_types=1);\n"
    . "// Generated by AMEA Stellar deployment; do not edit manually.\n"
    . "require_once " . $exportSingle($autoloadPath) . ";\n"
    . "define('AMEA_CONFIG_FILE', " . $exportSingle($configFile) . ");\n"
    . "define('AMEA_STATE_DIR', " . $exportSingle($stateDir) . ");\n"
    . "(new \\Amea\\Core\\Router())->dispatch(" . $exportSingle($role) . ");\n";

if (isset($options['output'])) {
    if (file_put_contents($options['output'], $php) === false) {
        fwrite(STDERR, "Unable to write rendered entry file.\n");
        exit(1);
    }
    chmod($options['output'], 0644);
    exit(0);
}

fwrite(STDOUT, $php);
exit(0);
